//! Mises à jour complètes du système (`pacman -Syu`) lancées par Last1 Panel :
//! jamais à l'aveugle. Avant chacune, ce que les dépôts vont installer est lu
//! sur une copie des listes de paquets (comme `checkupdates`) ; une mise à
//! jour qui casserait le bureau est arrêtée avant d'avoir rien changé.
//!
//! Hyprland 0.57 ne lit plus les fichiers `.conf` : passé de 0.56 à 0.57 sans
//! `hyprland.lua` à soi, le bureau démarre sur une configuration d'exemple
//! (clavier, raccourcis, barre et applications perdus). Rapport du
//! 2026-11-04.

/// Fonction shell `last1_syu` (à la place de `pacman -Syu`), pour les
/// scripts lancés en root par pkexec.
pub const GUARD: &str = r#"last1_syu() {
  if pacman -Q hyprland >/dev/null 2>&1; then
    db=$(mktemp -d)
    ln -s /var/lib/pacman/local "$db/local"
    pacman -Sy --dbpath "$db" --logfile /dev/null >/dev/null 2>&1 || true
    now=$(pacman -Q hyprland | awk '{print $2}')
    next=$(pacman -Si --dbpath "$db" hyprland 2>/dev/null | awk '/^Version/ {print $3; exit}')
    rm -rf "$db"
    if [ -n "$next" ] && [ "$(vercmp "$now" 0.57)" -lt 0 ] && [ "$(vercmp "$next" 0.57)" -ge 0 ]; then
      home=$(getent passwd "${PKEXEC_UID:-0}" | cut -d: -f6)
      lua="$home/.config/hypr/hyprland.lua"
      # Bureau Signal : go-to-linux pose son hyprland.lua pendant la mise à
      # jour (crochet de pacman).
      gtl=""
      [ -e "$home/.config/hypr/gtl-machine.conf" ] && [ -e /etc/pacman.d/hooks/gtl-hyprland.hook ] && gtl=1
      if [ -z "$gtl" ] && { [ ! -s "$lua" ] || grep -q 'AUTOGENERATED HYPRLAND CONFIG' "$lua"; }; then
        echo "Mise à jour arrêtée, rien n'a changé : Hyprland $next ne lit plus la configuration de votre bureau (hyprland.conf) ; il démarrerait sans vos raccourcis, votre clavier ni votre barre. / Update stopped, nothing changed: Hyprland $next no longer reads your desktop's configuration (hyprland.conf)." >&2
        return 1
      fi
    fi
  fi
  pacman -Syu "$@"
}"#;

/// Le script avec ses `pacman -Syu` remplacés par `last1_syu`, défini en tête.
pub fn guarded(script: &str) -> String {
    if !script.contains("pacman -Syu") {
        return script.to_string();
    }
    format!("{GUARD}\n{}", script.replace("pacman -Syu", "last1_syu"))
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;
    use std::process::Command;

    #[test]
    fn untouched_without_full_update() {
        let script = "pacman -S --needed --noconfirm lact";
        assert_eq!(guarded(script), script);
        let full = guarded("pacman -S lact || pacman -Syu --needed --noconfirm lact");
        assert!(full.starts_with("last1_syu() {"));
        assert!(full.ends_with("pacman -S lact || last1_syu --needed --noconfirm lact"));
    }

    /// Faux pacman et vercmp : Hyprland 0.56 installé, 0.57 dans les dépôts.
    #[test]
    fn hyprland_057_without_lua_config_stops_the_update() {
        let dir = tempfile::tempdir().unwrap();
        let bin = dir.path().join("bin");
        let home = dir.path().join("home");
        fs::create_dir_all(&bin).unwrap();
        fs::create_dir_all(home.join(".config/hypr")).unwrap();
        let log = dir.path().join("pacman.log");
        let script = |name: &str, body: &str| {
            let path = bin.join(name);
            fs::write(&path, format!("#!/bin/sh\n{body}\n")).unwrap();
            fs::set_permissions(&path, std::os::unix::fs::PermissionsExt::from_mode(0o755)).unwrap();
        };
        script(
            "pacman",
            &format!(
                r#"case "$1" in
  -Q) echo "hyprland 0.56.2-4" ;;
  -Si) echo "Version         : 0.57.1-1" ;;
  -Sy) ;;
  -Syu) echo "$@" >> {log} ;;
esac"#,
                log = log.display()
            ),
        );
        script(
            "vercmp",
            r#"[ "$1" = "$2" ] && echo 0 && exit; [ "$(printf '%s\n%s\n' "$1" "$2" | sort -V | head -1)" = "$1" ] && echo -1 || echo 1"#,
        );
        script("getent", &format!("echo \"u:x:1000:1000::{}:/bin/sh\"", home.display()));
        let run = || {
            Command::new("/bin/sh")
                .args(["-c", &guarded("set -e\npacman -Syu --noconfirm")])
                .env("PATH", format!("{}:/usr/bin:/bin", bin.display()))
                .env("PKEXEC_UID", "1000")
                .output()
                .unwrap()
        };
        // Pas de hyprland.lua : arrêtée, pacman -Syu jamais lancé.
        let stopped = run();
        assert!(!stopped.status.success());
        assert!(String::from_utf8_lossy(&stopped.stderr).contains("Mise à jour arrêtée"));
        assert!(!log.exists());
        // Celui qu'Hyprland génère tout seul ne compte pas.
        fs::write(home.join(".config/hypr/hyprland.lua"), "-- AUTOGENERATED HYPRLAND CONFIG\n").unwrap();
        assert!(!run().status.success());
        // Une vraie configuration Lua : la mise à jour se fait.
        fs::write(home.join(".config/hypr/hyprland.lua"), "hl.config({})\n").unwrap();
        assert!(run().status.success());
        assert_eq!(fs::read_to_string(&log).unwrap().trim(), "-Syu --noconfirm");
    }
}
