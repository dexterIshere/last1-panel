//! Ce que Hyprland reproche à la configuration du joueur : réglages
//! dépréciés (« You are using 1 deprecated config option », à chaque
//! ouverture de session) et erreurs de lecture (barre rouge). Joint aux
//! rapports de performances pour voir sur tous les PC ce qui casse après
//! une mise à jour de Hyprland.

use crate::exec::Exec;
use serde::Serialize;

#[derive(Debug, Clone, Default, PartialEq, Serialize)]
pub struct Health {
    /// `hyprctl version` : « 0.57.1 ».
    pub version: String,
    /// `hyprctl deprecated-config` : « option: explication ».
    pub deprecated: Vec<String>,
    /// `hyprctl configerrors` : « fichier:ligne: erreur ».
    #[serde(rename = "configErrors")]
    pub config_errors: Vec<String>,
}

/// Liste JSON de `hyprctl -j …` ; lignes vides retirées.
fn list(json: &str) -> Vec<String> {
    serde_json::from_str::<Vec<String>>(json)
        .unwrap_or_default()
        .into_iter()
        .map(|line| line.trim().to_string())
        .filter(|line| !line.is_empty())
        .collect()
}

/// « Hyprland 0.57.1 built from branch … » → « 0.57.1 ».
fn version(text: &str) -> String {
    let json: serde_json::Value = serde_json::from_str(text).unwrap_or_default();
    let tag = json["tag"].as_str().or_else(|| json["version"].as_str()).unwrap_or_default();
    tag.trim_start_matches('v').split('-').next().unwrap_or_default().to_string()
}

/// L'état de Hyprland en cours (`-i 0` : la session du joueur, même sans
/// HYPRLAND_INSTANCE_SIGNATURE dans le service) ; `None` hors Hyprland.
pub fn read(exec: &dyn Exec) -> Option<Health> {
    let run = |what: &str| {
        exec.run("hyprctl", &["-i".to_string(), "0".to_string(), "-j".to_string(), what.to_string()])
            .ok()
            .filter(|out| out.success())
            .map(|out| out.stdout)
    };
    let version = version(&run("version")?);
    Some(Health {
        version,
        deprecated: list(&run("deprecated-config").unwrap_or_default()),
        config_errors: list(&run("configerrors").unwrap_or_default()),
    })
}

/// Ce que `hyprctl` ne dit pas : la session ouverte sur l'exemple de
/// Hyprland (configuration du joueur ignorée), hyprland.conf sans Lua avec
/// Hyprland 0.57, ou une reprise automatique refusée (`failed`).
pub fn with_desktop(mut health: Health, hypr_dir: &std::path::Path, failed: &std::path::Path) -> Health {
    let lua_era = crate::system::update_check::needs_lua(&health.version);
    if super::hypr_lua::config_lost(hypr_dir) {
        health.config_errors.push("bureau : exemple de Hyprland à la place de la configuration du joueur".into());
    } else if lua_era && super::hypr_migrate::lost(hypr_dir) {
        health.config_errors.push("bureau : hyprland.conf sans hyprland.lua (ignoré par Hyprland 0.57)".into());
    }
    if let Ok(reason) = std::fs::read_to_string(failed) {
        let reason: String = reason.chars().take(300).collect();
        health.config_errors.push(format!("bureau : reprise automatique refusée : {reason}"));
    }
    health
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::exec::{FakeExec, Output};

    fn ok(stdout: &str) -> Output {
        Output { status: 0, stdout: stdout.into(), stderr: String::new() }
    }

    #[test]
    fn deprecated_options_and_errors_are_read() {
        let exec = FakeExec::new()
            .on_args(
                "hyprctl",
                &["-i", "0", "-j", "version"],
                ok(r#"{"branch": "v0.57.1", "tag": "v0.57.1", "version": "0.57.1"}"#),
            )
            .on_args(
                "hyprctl",
                &["-i", "0", "-j", "deprecated-config"],
                ok(r#"["dwindle:special_scale_factor: Use workspace rules to achieve the same effect"]"#),
            )
            .on_args("hyprctl", &["-i", "0", "-j", "configerrors"], ok("[\n\t\"\"\n]\n"));
        assert_eq!(
            read(&exec).unwrap(),
            Health {
                version: "0.57.1".into(),
                deprecated: vec!["dwindle:special_scale_factor: Use workspace rules to achieve the same effect".into()],
                config_errors: Vec::new(),
            }
        );
        assert!(read(&FakeExec::new().without("hyprctl")).is_none());
    }

    #[test]
    fn example_config_and_refused_restore_are_reported() {
        let dir = tempfile::tempdir().unwrap();
        std::fs::write(dir.path().join("hyprland.conf"), "").unwrap();
        std::fs::write(dir.path().join("hyprland.lua"), "-- AUTOGENERATED HYPRLAND CONFIG.\n").unwrap();
        let failed = dir.path().join("failed.txt");
        std::fs::write(&failed, "Hyprland refuse la conversion : x").unwrap();
        let health = with_desktop(Health { version: "0.57.1".into(), ..Health::default() }, dir.path(), &failed);
        assert_eq!(health.config_errors.len(), 2);
        assert!(health.config_errors[0].contains("exemple de Hyprland"));
        assert!(health.config_errors[1].contains("refusée"));
    }
}
