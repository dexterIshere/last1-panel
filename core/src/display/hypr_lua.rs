//! Hyprland 0.57 et suivants : la configuration est en Lua (hyprland.lua),
//! les `.conf` ne sont plus lus et `hyprctl keyword` est refusé. Last1 Panel
//! écrit ses réglages dans ses propres fichiers (`last1-panel-*.lua`), que
//! hyprland.lua charge par une ligne `pcall(require, …)` ajoutée une fois
//! (une erreur dans l'un ne coupe pas la suite de la configuration), et les
//! applique aussitôt par `hyprctl eval`.
//!
//! Syntaxe d'après les sources de Hyprland (example/hyprland.lua,
//! hyprtester/test.lua, src/config/lua/bindings/LuaBindingsConfigRules.cpp).

use crate::error::CoreResult;
use std::fs;
use std::path::Path;

/// Marque de la configuration d'exemple que Hyprland crée s'il n'en trouve pas.
pub const AUTOGENERATED: &str = "AUTOGENERATED HYPRLAND CONFIG";

/// Configuration Lua en service.
pub fn uses_lua(hypr_dir: &Path) -> bool {
    hypr_dir.join("hyprland.lua").exists()
}

/// Hyprland est passé en Lua sans reprendre la configuration de
/// l'utilisateur : il démarre sur son exemple, hyprland.conf est ignoré.
pub fn config_lost(hypr_dir: &Path) -> bool {
    hypr_dir.join("hyprland.conf").exists()
        && fs::read_to_string(hypr_dir.join("hyprland.lua")).is_ok_and(|text| text.contains(AUTOGENERATED))
}

/// Chaîne Lua entre guillemets.
pub fn string(text: &str) -> String {
    let mut out = String::from("\"");
    for c in text.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// hyprland.lua charge `module` (dans le même dossier), une seule fois.
pub fn ensure_required(hypr_dir: &Path, module: &str) -> CoreResult<()> {
    let main = hypr_dir.join("hyprland.lua");
    let text = fs::read_to_string(&main).unwrap_or_default();
    let line = format!("pcall(require, \"./{module}\")");
    if text.lines().any(|l| l.trim() == line) {
        return Ok(());
    }
    let mut new = text;
    if !new.is_empty() && !new.ends_with('\n') {
        new.push('\n');
    }
    new.push_str(&format!("\n-- Last1 Panel (fichier qu'il réécrit à chaque réglage)\n{line}\n"));
    fs::write(&main, new)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn required_once_and_lost_config_seen() {
        let dir = tempfile::tempdir().unwrap();
        fs::write(dir.path().join("hyprland.lua"), "hl.config({})").unwrap();
        ensure_required(dir.path(), "last1-panel-mouse.lua").unwrap();
        ensure_required(dir.path(), "last1-panel-mouse.lua").unwrap();
        let text = fs::read_to_string(dir.path().join("hyprland.lua")).unwrap();
        assert_eq!(text.matches("pcall(require, \"./last1-panel-mouse.lua\")").count(), 1);
        assert!(text.starts_with("hl.config({})\n"));
        assert_eq!(string("a \"b\" \\c"), r#""a \"b\" \\c""#);

        assert!(!config_lost(dir.path()));
        fs::write(dir.path().join("hyprland.conf"), "monitor = ,preferred,auto,1\n").unwrap();
        assert!(!config_lost(dir.path()), "vraie configuration Lua");
        fs::write(dir.path().join("hyprland.lua"), "-- AUTOGENERATED HYPRLAND CONFIG.\n").unwrap();
        assert!(config_lost(dir.path()));
    }
}
